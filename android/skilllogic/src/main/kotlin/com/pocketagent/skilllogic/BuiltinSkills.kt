 * | 文档结构速查 | Diátaxis 框架 |
 * | 决策记录速查 | DACI / RAPID、ADR 实践 |
 *
 * ## 为什么分「做法」与「速查」
 *
 * 前八条是**流程**：从零做起时按它走。后四条是**规矩**：写的时候随手查，
 * 回答「这句该不该这么写」「这个图该怎么画」。两类都进清单，但用户
 * 打 `/` 时看到的是同一个列表 —— 分不分类型是给我看的，不是给他看的。
 *
 * ## 为什么正文里反复出现「不要」
 *
 * 因为正向要求模型会自己发挥，负向要求不会。写「标题写结论」它可能写成
 * 「关于成本的分析」；再补一句「不写主题词」才稳得住。这和
 * `RoleplayDiscipline` 的教训是同一条：禁令必须配替代动作，
 * 否则模型只会换个方式犯同一个错。
 *
 * ## 顺序
 *
 * 列表顺序 = `/` 面板顺序 = 提示词清单顺序。最常用的放前面
 * （演示、文档、表格），因为清单本身有长度预算，先列的被裁掉概率低。
 * 四张速查放最后：它们是查的时候用，不是开工时用。
 *
 * ## 长度
 *
 * 每条正文都在 [Skill.MAX_BODY_CHARS] 之内，[BuiltinSkillsTest] 会守这个上限 ——
 * 技能正文进系统提示词，写太长会把人格、记忆、世界书挤出去。
 */
