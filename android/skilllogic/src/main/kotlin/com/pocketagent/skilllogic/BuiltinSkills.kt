    /** 按 id 取。**大小写敏感** —— id 是我们自己生成的，不该出现大小写歧义。 */
    fun byId(id: String): Skill? = all.firstOrNull { it.id == id }

    /** 按名字取（`/` 面板插进文本的是中文名，解析时要用）。 */
    fun byName(name: String): Skill? = all.firstOrNull { it.name == name }
