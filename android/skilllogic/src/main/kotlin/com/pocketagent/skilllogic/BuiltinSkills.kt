 * ## 这些正文是怎么来的
 *
 * 不是"提示词模板"，也不是从别处抄的清单。每一条都对应一类**真实会返工**的问题：
 *
 * | 技能 | 不加它时最常见的返工理由 |
 * |---|---|
 * | 演示文稿 | 「页数不少，但看完不知道你想让我做什么」 |
 * | 文档报告 | 「结论埋在第三页」 |
 * | 表格数据 | 「表头没单位，合并单元格没法筛」 |
 * | 调研对比 | 「只挑了对某一家有利的维度」 |
 * | 会议纪要 | 「记了谁说了什么，没记谁要做什么」 |
 * | 项目计划 | 「里程碑全是日期，没有产物」 |
 * | 方案评审 | 「说了十件小事，最贵的那件没提」 |
 * | 邮件消息 | 「第一段寒暄，第二段才说正事」 |
 *
 * ## 为什么正文里反复出现「不要」
 *
 * 因为**正向要求模型会自己发挥，负向要求不会**。写「标题写结论」它可能写成
 * 「关于成本的分析」；再补一句「不写主题词」才稳得住。这和 `RoleplayDiscipline`
 * 的教训是同一条：禁令必须配替代动作，否则模型只会换个方式犯同一个错。
 *
 * ## 顺序
 *
 * 列表顺序 = `/` 面板顺序 = 提示词清单顺序。把最常用的放前面
 * （演示、文档、表格），因为清单本身也有长度预算，先列的被裁掉的概率低。
 */
